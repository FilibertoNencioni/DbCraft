// Dialect aware DDL generation (CREATE / ALTER / DROP) for tables, columns,
// keys, indexes and comments.
//
// Every method returns a list of statements WITHOUT terminators, ready to be
// executed one by one through ODBC (Oracle rejects a trailing ';'). Entries
// made only of `--` lines are comments: they are rendered in scripts and
// skipped on execution. [DdlBuilder.render] joins the statements into a script.

import '../../model/db_objects.dart';
import '../../services/sql_dialect.dart';
import '../design/capabilities.dart';
import 'schema_model.dart';

/// True when [sql] contains only comments and blank lines.
bool isCommentOnly(String sql) => sql.split('\n').every((l) => l.trim().isEmpty || l.trimLeft().startsWith('--'));

/// Statements of [statements] that must be sent to the server.
List<String> executableStatements(List<String> statements) => statements.where((s) => !isCommentOnly(s)).toList();

/// Prefixes of the names given to new constraints and indexes.
class NamingConvention {
  const NamingConvention({
    this.primaryKey = 'pk_',
    this.unique = 'uq_',
    this.check = 'ck_',
    this.foreignKey = 'fk_',
    this.index = 'ix_',
  });

  final String primaryKey;
  final String unique;
  final String check;
  final String foreignKey;
  final String index;
}

class DdlBuilder {
  DdlBuilder(this.dialect, {this.naming = const NamingConvention()}) : caps = DesignCapabilities.of(dialect);

  final SqlDialect dialect;
  final DesignCapabilities caps;
  final NamingConvention naming;

  DbFamily get family => dialect.family;

  bool get _mariaDb => dialect.isMariaDb;

  String q(String name) => dialect.quoteIdent(name);

  String tableRef(TableDef t) => dialect.qualified(t.catalog, t.schema, t.name);

  String _cols(List<String> cols) => cols.map(q).join(', ');

  String _comment(String text) => text.split('\n').map((l) => '-- $l').join('\n');

  /// Joins [statements] into a script with `;` terminators.
  String render(List<String> statements) {
    final sb = StringBuffer();
    for (final s in statements) {
      if (isCommentOnly(s)) {
        if (sb.isNotEmpty && !sb.toString().endsWith('\n\n')) sb.writeln();
        sb.writeln(s);
      } else {
        sb.writeln('$s;');
        sb.writeln();
      }
    }
    return sb.toString().trimRight();
  }

  // -------------------------------------------------------------------------
  // Column definitions
  // -------------------------------------------------------------------------

  /// Type declaration of [c] for this dialect.
  String columnType(ColumnDef c) {
    final type = c.type.trim();
    if (type.contains('(') || c.size == null) return type;
    if (c.size == -1) {
      final canon = canonicalType(type);
      switch (family) {
        case DbFamily.sqlServer:
          return '$type(MAX)';
        case DbFamily.mysql:
          return canon.contains('binary') ? 'LONGBLOB' : 'LONGTEXT';
        case DbFamily.oracle:
          return canon.contains('binary') ? 'BLOB' : (canon == 'nvarchar' ? 'NCLOB' : 'CLOB');
        default:
          return type;
      }
    }
    if (c.scale != null && c.scale! > 0) return '$type(${c.size},${c.scale})';
    return '$type(${c.size})';
  }

  String? _identity(ColumnDef c) {
    final seed = c.identitySeed, step = c.identityIncrement;
    final custom = (seed != null && seed != 1) || (step != null && step != 1);
    return switch (family) {
      DbFamily.sqlServer => 'IDENTITY(${seed ?? 1},${step ?? 1})',
      DbFamily.mysql => null, // AUTO_INCREMENT is appended at the end
      DbFamily.sqlite => null, // only as INTEGER PRIMARY KEY AUTOINCREMENT
      DbFamily.snowflake => custom ? 'AUTOINCREMENT START ${seed ?? 1} INCREMENT ${step ?? 1}' : 'AUTOINCREMENT',
      DbFamily.bigquery || DbFamily.cassandra => null,
      _ =>
        custom
            ? 'GENERATED BY DEFAULT AS IDENTITY (START WITH ${seed ?? 1} INCREMENT BY ${step ?? 1})'
            : 'GENERATED BY DEFAULT AS IDENTITY',
    };
  }

  /// COLLATE clause of [c] (empty when it has none or the DBMS has no
  /// column collations).
  String _collate(ColumnDef c) {
    final coll = c.collation?.trim();
    if (coll == null || coll.isEmpty) return '';
    return switch (family) {
      DbFamily.postgres => ' COLLATE "${coll.replaceAll('"', '""')}"',
      DbFamily.snowflake => ' COLLATE ${dialect.stringLiteral(coll)}',
      DbFamily.db2 || DbFamily.bigquery || DbFamily.cassandra => '',
      _ => ' COLLATE $coll',
    };
  }

  /// Generated column clause of [c].
  String _computed(ColumnDef c) {
    final e = c.computed!.trim();
    final stored = c.computedStored;
    return switch (family) {
      DbFamily.sqlServer => 'AS ($e)${stored ? ' PERSISTED' : ''}',
      DbFamily.postgres || DbFamily.db2 => 'GENERATED ALWAYS AS ($e)${family == DbFamily.postgres ? ' STORED' : ''}',
      DbFamily.oracle => 'GENERATED ALWAYS AS ($e) VIRTUAL',
      DbFamily.firebird => 'COMPUTED BY ($e)',
      DbFamily.snowflake => 'AS ($e)',
      _ => 'GENERATED ALWAYS AS ($e) ${stored ? 'STORED' : 'VIRTUAL'}',
    };
  }

  /// Full column definition used by CREATE TABLE and ADD COLUMN.
  String columnDefinition(ColumnDef c, {bool sqliteRowId = false}) {
    if (c.isComputed) {
      // SQL Server computed columns have no declared type.
      final sb = StringBuffer(q(c.name));
      if (family != DbFamily.sqlServer) sb.write(' ${columnType(c)}${_collate(c)}');
      sb.write(' ${_computed(c)}');
      final nn = !c.nullable && (family != DbFamily.sqlServer || c.computedStored) && family != DbFamily.firebird;
      if (nn) sb.write(' NOT NULL');
      if (family == DbFamily.mysql && c.comment != null && c.comment!.isNotEmpty) {
        sb.write(' COMMENT ${dialect.stringLiteral(c.comment!)}');
      }
      return sb.toString();
    }
    final collate = _collate(c);
    final sb = StringBuffer('${q(c.name)} ${columnType(c)}');
    if (family != DbFamily.firebird) sb.write(collate);
    if (sqliteRowId) {
      sb.write(' PRIMARY KEY AUTOINCREMENT');
      return sb.toString();
    }
    if (c.autoIncrement) {
      final id = _identity(c);
      if (id != null) sb.write(' $id');
    }
    final def = c.defaultValue?.trim();
    if (!c.autoIncrement && def != null && def.isNotEmpty && family != DbFamily.cassandra) {
      final named = family == DbFamily.sqlServer && c.defaultName != null && c.defaultName!.isNotEmpty;
      sb.write(named ? ' CONSTRAINT ${q(c.defaultName!)} DEFAULT $def' : ' DEFAULT $def');
    }
    if (!c.nullable && family != DbFamily.cassandra) sb.write(' NOT NULL');
    if (family == DbFamily.firebird) sb.write(collate);
    if (family == DbFamily.mysql) {
      if (c.autoIncrement) sb.write(' AUTO_INCREMENT');
      if (c.comment != null && c.comment!.isNotEmpty) sb.write(' COMMENT ${dialect.stringLiteral(c.comment!)}');
    }
    return sb.toString();
  }

  // -------------------------------------------------------------------------
  // Names
  // -------------------------------------------------------------------------

  /// Longest identifier accepted by the DBMS.
  int get maxIdentifierLength {
    final v = dialect.version;
    return switch (family) {
      DbFamily.oracle => v != null && !v.atLeast(12, 2) ? 30 : 128,
      DbFamily.postgres => 63,
      DbFamily.mysql => 64,
      DbFamily.firebird => v != null && !v.atLeast(4) ? 31 : 63,
      DbFamily.snowflake => 255,
      DbFamily.sqlite => 1000,
      _ => 128,
    };
  }

  /// Name for a new constraint or index of [t]: the prefix of the [kind]
  /// (null: an index) followed by the table and the [columns] (or, for a
  /// foreign key, the referenced table; for a check, [n]). Too long names
  /// are shortened with a hash that keeps them distinct.
  String autoName(TableDef t, ConstraintKind? kind, {List<String> columns = const [], String? refTable, int n = 1}) {
    final base = switch (kind) {
      ConstraintKind.primaryKey => '${naming.primaryKey}${t.name}',
      ConstraintKind.unique => '${naming.unique}${t.name}_${columns.join('_')}',
      ConstraintKind.check => '${naming.check}${t.name}_$n',
      ConstraintKind.foreignKey => '${naming.foreignKey}${t.name}_${refTable ?? columns.join('_')}',
      null => '${naming.index}${t.name}_${columns.join('_')}',
    };
    final clean = base.replaceAll(RegExp(r'[^A-Za-z0-9_$#]'), '_');
    final max = maxIdentifierLength;
    if (clean.length <= max) return clean;
    var h = 0;
    for (final u in clean.codeUnits) {
      h = (h * 31 + u) & 0xFFFFF;
    }
    final hash = h.toRadixString(16).padLeft(5, '0');
    return '${clean.substring(0, max - 6)}_$hash';
  }

  String _comment2(String text) => _comment('$text (non supportato)');

  // -------------------------------------------------------------------------
  // Tables
  // -------------------------------------------------------------------------

  /// CREATE TABLE with columns and primary key. Foreign keys are created
  /// separately (after every table exists) unless [withForeignKeys]; SQLite
  /// always declares them inline because it cannot add them later.
  List<String> createTable(
    TableDef t, {
    bool withForeignKeys = false,
    bool withIndexes = true,
    bool withComments = true,
  }) {
    final pk = t.primaryKey;
    final pkCols = pk?.columns ?? const <String>[];
    // SQLite: an auto-increment column must be the INTEGER PRIMARY KEY.
    String? rowId;
    if (family == DbFamily.sqlite && pkCols.length == 1) {
      final c = t.column(pkCols.first);
      if (c != null && c.autoIncrement) rowId = c.name;
    }
    final lines = <String>[
      for (final c in t.columns)
        '\t${columnDefinition(c.name == rowId ? c.copyWith(type: 'INTEGER', size: null, scale: null) : c, sqliteRowId: c.name == rowId)}',
    ];
    if (pkCols.isNotEmpty && rowId == null) lines.add('\t${_pkClause(pk!)}');
    for (final u in t.uniques) {
      lines.add('\t${_uniqueClause(u)}');
    }
    final notes = <String>[];
    for (final c in t.checks) {
      if (caps.has(DesignFeature.checkConstraints) || family == DbFamily.sqlite) {
        lines.add('\t${_checkClause(c)}');
      } else {
        notes.add(
          _comment2('Vincolo CHECK ${c.name ?? c.expression} ignorato: ${caps.reason(DesignFeature.checkConstraints)}'),
        );
      }
    }
    if (withForeignKeys || family == DbFamily.sqlite) {
      for (final fk in t.foreignKeys) {
        lines.add('\t${_fkClause(fk, t)}');
      }
    }
    final o = t.options;
    final unlogged = family == DbFamily.postgres && o['unlogged'] == 'true' ? 'UNLOGGED ' : '';
    final sb = StringBuffer('CREATE ${unlogged}TABLE ${tableRef(t)} (\n${lines.join(',\n')}\n)');
    switch (family) {
      case DbFamily.postgres || DbFamily.oracle:
        if (o['tablespace']?.isNotEmpty ?? false) sb.write(' TABLESPACE ${q(o['tablespace']!)}');
      case DbFamily.db2:
        if (o['tablespace']?.isNotEmpty ?? false) sb.write(' IN ${q(o['tablespace']!)}');
      case DbFamily.sqlServer:
        if (o['filegroup']?.isNotEmpty ?? false) sb.write(' ON ${q(o['filegroup']!)}');
      case DbFamily.mysql:
        if (o['engine']?.isNotEmpty ?? false) sb.write(' ENGINE=${o['engine']}');
        if (o['charset']?.isNotEmpty ?? false) sb.write(' DEFAULT CHARSET=${o['charset']}');
        if (o['collation']?.isNotEmpty ?? false) sb.write(' COLLATE=${o['collation']}');
      default:
        break;
    }
    final out = <String>[...notes, sb.toString()];
    if (family == DbFamily.mysql && t.comment != null && t.comment!.isNotEmpty) {
      out[out.length - 1] = '${out.last} COMMENT=${dialect.stringLiteral(t.comment!)}';
    }
    // Constraints created disabled.
    for (final c in [?t.primaryKey, ...t.uniques, ...t.checks, if (withForeignKeys) ...t.foreignKeys]) {
      if (!_state(c).enabled && caps.has(DesignFeature.disableConstraints)) {
        out.addAll(setConstraintEnabled(t, c, false));
      }
    }
    if (withIndexes) {
      for (final ix in t.indexes) {
        out.addAll(createIndex(t, ix));
      }
    }
    if (withComments && family != DbFamily.mysql) {
      if (t.comment != null && t.comment!.isNotEmpty) out.addAll(tableComment(t, t.comment));
      for (final c in t.columns) {
        if (c.comment != null && c.comment!.isNotEmpty) out.addAll(columnComment(t, c));
      }
    }
    return out;
  }

  /// Script that recreates the table described by the ODBC metadata [d]
  /// (DDL page, "Genera DDL"): CREATE TABLE with keys, then indexes and
  /// comments. ODBC does not expose view definitions, so for views only the
  /// columns are listed.
  String tableScript(TableDetails d) {
    final t = d.table;
    if (t.isView) {
      return [
        '-- Vista ${dialect.tableName(t)}: la definizione non è esposta via ODBC.',
        '-- Colonne:',
        for (final c in d.columns) '--   ${c.name} ${c.fullType}',
      ].join('\n');
    }
    return render(createTable(TableDef.fromDetails(d), withForeignKeys: true));
  }

  List<String> dropTable(TableDef t) => [
    family == DbFamily.oracle ? 'DROP TABLE ${tableRef(t)} CASCADE CONSTRAINTS' : 'DROP TABLE ${tableRef(t)}',
  ];

  /// Renames [t] (current name) to [newName].
  List<String> renameTable(TableDef t, String newName) {
    final to = t.copyWith(name: newName);
    switch (family) {
      case DbFamily.sqlServer:
        final from = dialect.qualified(null, t.schema, t.name);
        return ['EXEC sp_rename ${_n(from)}, ${_n(newName)}'];
      case DbFamily.mysql:
        return ['RENAME TABLE ${tableRef(t)} TO ${tableRef(to)}'];
      case DbFamily.db2:
        return ['RENAME TABLE ${tableRef(t)} TO ${q(newName)}'];
      case DbFamily.firebird:
        return [_comment('Firebird non supporta la ridenominazione di tabelle: ${t.name} → $newName (non supportato)')];
      default:
        return ['ALTER TABLE ${tableRef(t)} RENAME TO ${q(newName)}'];
    }
  }

  /// N'…' literal for SQL Server system procedures.
  String _n(String s) => 'N${dialect.stringLiteral(s)}';

  // -------------------------------------------------------------------------
  // Columns
  // -------------------------------------------------------------------------

  List<String> addColumn(TableDef t, ColumnDef c) {
    final def = columnDefinition(c);
    final out = <String>[];
    if (!c.nullable && (c.defaultValue == null || c.defaultValue!.trim().isEmpty) && !c.autoIncrement) {
      out.add(_comment('Attenzione: ${c.name} è NOT NULL senza DEFAULT, fallisce se la tabella contiene righe'));
    }
    switch (family) {
      case DbFamily.sqlServer || DbFamily.oracle || DbFamily.firebird:
        out.add('ALTER TABLE ${tableRef(t)} ADD $def');
      default:
        out.add('ALTER TABLE ${tableRef(t)} ADD COLUMN $def');
    }
    if (family != DbFamily.mysql && c.comment != null && c.comment!.isNotEmpty) out.addAll(columnComment(t, c));
    return out;
  }

  List<String> dropColumn(TableDef t, String column) => [
    family == DbFamily.firebird
        ? 'ALTER TABLE ${tableRef(t)} DROP ${q(column)}'
        : 'ALTER TABLE ${tableRef(t)} DROP COLUMN ${q(column)}',
  ];

  List<String> renameColumn(TableDef t, String from, String to) {
    switch (family) {
      case DbFamily.sqlServer:
        final path = '${dialect.qualified(null, t.schema, t.name)}.${q(from)}';
        return ["EXEC sp_rename ${_n(path)}, ${_n(to)}, 'COLUMN'"];
      case DbFamily.firebird:
        return ['ALTER TABLE ${tableRef(t)} ALTER COLUMN ${q(from)} TO ${q(to)}'];
      default:
        return ['ALTER TABLE ${tableRef(t)} RENAME COLUMN ${q(from)} TO ${q(to)}'];
    }
  }

  /// Changes type, nullability and default of a column from [from] to [to]
  /// ([to].name is the current name of the column).
  List<String> alterColumn(TableDef t, ColumnDef from, ColumnDef to) {
    final table = tableRef(t);
    final col = q(to.name);
    final typeChanged = columnType(from).toLowerCase() != columnType(to).toLowerCase();
    final nullChanged = from.nullable != to.nullable;
    final defChanged = normalizeDefault(from.defaultValue) != normalizeDefault(to.defaultValue);
    final autoChanged = from.autoIncrement != to.autoIncrement;
    final commentChanged = (from.comment ?? '') != (to.comment ?? '');
    final collChanged =
        (to.collation ?? '').isNotEmpty && (from.collation ?? '').toLowerCase() != to.collation!.toLowerCase();
    final newDef = to.defaultValue?.trim();
    final hasDef = newDef != null && newDef.isNotEmpty;
    final out = <String>[];
    // A computed column holds no data of its own: it is recreated.
    if (from.isComputed || to.isComputed) {
      final computedChanged =
          from.isComputed != to.isComputed ||
          normalizeExpression(from.computed ?? '') != normalizeExpression(to.computed ?? '') ||
          from.computedStored != to.computedStored;
      if (computedChanged || typeChanged || nullChanged) {
        if (!from.isComputed) {
          out.add(_comment('Attenzione: i dati della colonna ${to.name} vanno persi, diventa una colonna calcolata'));
        }
        return [...out, ...dropColumn(t, from.name), ...addColumn(t, to)];
      }
    }
    if (autoChanged && family != DbFamily.mysql) {
      out.addAll(_alterIdentity(t, to));
    }
    if (collChanged) {
      switch (family) {
        case DbFamily.sqlServer:
          if (!typeChanged && !nullChanged) {
            out.add(
              'ALTER TABLE $table ALTER COLUMN $col ${columnType(to)}${_collate(to)}${to.nullable ? ' NULL' : ' NOT NULL'}',
            );
          }
        case DbFamily.postgres:
          if (!typeChanged) out.add('ALTER TABLE $table ALTER COLUMN $col TYPE ${columnType(to)}${_collate(to)}');
        case DbFamily.oracle:
          if (!typeChanged) out.add('ALTER TABLE $table MODIFY ($col COLLATE ${to.collation})');
        case DbFamily.mysql:
          break; // MODIFY COLUMN below
        default:
          out.add(_comment2('Modifica della collation di ${to.name}'));
      }
    }
    switch (family) {
      case DbFamily.mysql:
        if (typeChanged || nullChanged || defChanged || autoChanged || commentChanged || collChanged) {
          out.add('ALTER TABLE $table MODIFY COLUMN ${columnDefinition(to)}');
        }
        return out;
      case DbFamily.sqlServer:
        if (typeChanged || nullChanged) {
          out.add(
            'ALTER TABLE $table ALTER COLUMN $col ${columnType(to)}${_collate(to)}${to.nullable ? ' NULL' : ' NOT NULL'}',
          );
        }
        if (defChanged) {
          if (from.defaultValue != null && from.defaultValue!.trim().isNotEmpty) {
            final known = from.defaultName != null && from.defaultName!.isNotEmpty;
            out.add(
              known ? 'ALTER TABLE $table DROP CONSTRAINT ${q(from.defaultName!)}' : _mssqlDropDefault(t, to.name),
            );
          }
          if (hasDef) {
            final named = to.defaultName != null && to.defaultName!.isNotEmpty && to.defaultName != from.defaultName;
            out.add(
              'ALTER TABLE $table ADD ${named ? 'CONSTRAINT ${q(to.defaultName!)} ' : ''}DEFAULT $newDef FOR $col',
            );
          }
        }
      case DbFamily.oracle:
        final parts = <String>[
          if (typeChanged) columnType(to),
          if (defChanged) 'DEFAULT ${hasDef ? newDef : 'NULL'}',
          if (nullChanged) to.nullable ? 'NULL' : 'NOT NULL',
        ];
        if (parts.isNotEmpty) out.add('ALTER TABLE $table MODIFY ($col ${parts.join(' ')})');
      case DbFamily.postgres || DbFamily.generic:
        if (typeChanged) {
          final using = family == DbFamily.postgres ? ' USING $col::${columnType(to)}' : '';
          out.add('ALTER TABLE $table ALTER COLUMN $col TYPE ${columnType(to)}$using');
        }
        if (nullChanged) out.add('ALTER TABLE $table ALTER COLUMN $col ${to.nullable ? 'DROP' : 'SET'} NOT NULL');
        if (defChanged) {
          out.add('ALTER TABLE $table ALTER COLUMN $col ${hasDef ? 'SET DEFAULT $newDef' : 'DROP DEFAULT'}');
        }
      case DbFamily.db2 || DbFamily.snowflake:
        if (typeChanged) out.add('ALTER TABLE $table ALTER COLUMN $col SET DATA TYPE ${columnType(to)}');
        if (nullChanged) out.add('ALTER TABLE $table ALTER COLUMN $col ${to.nullable ? 'DROP' : 'SET'} NOT NULL');
        if (defChanged) {
          if (family == DbFamily.snowflake && hasDef) {
            out.add(
              _comment(
                'Snowflake non consente di impostare il DEFAULT di ${to.name} su una colonna esistente (non supportato)',
              ),
            );
          } else {
            out.add('ALTER TABLE $table ALTER COLUMN $col ${hasDef ? 'SET DEFAULT $newDef' : 'DROP DEFAULT'}');
          }
        }
        if (family == DbFamily.db2 && (typeChanged || nullChanged)) {
          out.add(_comment("Potrebbe essere necessario: CALL SYSPROC.ADMIN_CMD('REORG TABLE $table')"));
        }
      case DbFamily.firebird:
        if (typeChanged) out.add('ALTER TABLE $table ALTER COLUMN $col TYPE ${columnType(to)}');
        if (nullChanged) out.add('ALTER TABLE $table ALTER $col ${to.nullable ? 'DROP' : 'SET'} NOT NULL');
        if (defChanged) {
          out.add('ALTER TABLE $table ALTER COLUMN $col ${hasDef ? 'SET DEFAULT $newDef' : 'DROP DEFAULT'}');
        }
      case DbFamily.sqlite:
        if (typeChanged || nullChanged || defChanged || autoChanged) {
          out.add(
            _comment(
              'SQLite non supporta ALTER COLUMN su ${to.name}: è necessario ricostruire la tabella (non supportato)',
            ),
          );
        }
      default:
        if (typeChanged || nullChanged || defChanged) {
          out.add(_comment('Modifica della colonna ${to.name} non supportata da ${dialect.dbmsName} (non supportato)'));
        }
    }
    if (commentChanged) out.addAll(columnComment(t, to, previous: from.comment));
    return out;
  }

  /// Adds or removes the identity property of [to] (an existing column).
  List<String> _alterIdentity(TableDef t, ColumnDef to) {
    final table = tableRef(t), col = q(to.name);
    final add = to.autoIncrement;
    switch (family) {
      case DbFamily.postgres:
        return [
          add
              ? 'ALTER TABLE $table ALTER COLUMN $col ADD ${_identity(to)}'
              : 'ALTER TABLE $table ALTER COLUMN $col DROP IDENTITY IF EXISTS',
        ];
      case DbFamily.oracle when dialect.version == null || dialect.version!.atLeast(12):
        return [
          add ? 'ALTER TABLE $table MODIFY ($col ${_identity(to)})' : 'ALTER TABLE $table MODIFY ($col DROP IDENTITY)',
        ];
      case DbFamily.db2:
        return [
          add
              ? 'ALTER TABLE $table ALTER COLUMN $col SET ${_identity(to)}'
              : 'ALTER TABLE $table ALTER COLUMN $col DROP IDENTITY',
        ];
      default:
        return [
          _comment(
            'La modifica di identity/auto-increment di ${to.name} richiede di ricreare la colonna (non supportato)',
          ),
        ];
    }
  }

  /// SQL Server keeps defaults in named constraints: look the name up and drop it.
  String _mssqlDropDefault(TableDef t, String column) {
    final obj = dialect.qualified(null, t.schema, t.name);
    return 'DECLARE @df sysname\n'
        'SELECT @df = dc.name FROM sys.default_constraints dc '
        'JOIN sys.columns c ON c.object_id = dc.parent_object_id AND c.column_id = dc.parent_column_id '
        'WHERE dc.parent_object_id = OBJECT_ID(${_n(obj)}) AND c.name = ${_n(column)}\n'
        "IF @df IS NOT NULL EXEC(N'ALTER TABLE ${obj.replaceAll("'", "''")} DROP CONSTRAINT [' + @df + N']')";
  }

  // -------------------------------------------------------------------------
  // Constraints and indexes
  // -------------------------------------------------------------------------

  String _named(String? name) => name != null && name.isNotEmpty ? 'CONSTRAINT ${q(name)} ' : '';

  /// DEFERRABLE clause (PostgreSQL, Oracle; SQLite only for foreign keys).
  String _deferrable(ConstraintState st, {bool foreignKey = false}) {
    if (!st.deferrable) return '';
    final ok = caps.has(DesignFeature.deferrableConstraints) && (family != DbFamily.sqlite || foreignKey);
    if (!ok) return '';
    return ' DEFERRABLE INITIALLY ${st.initiallyDeferred ? 'DEFERRED' : 'IMMEDIATE'}';
  }

  String _pkClause(PrimaryKeyDef pk) {
    final clustered = family == DbFamily.sqlServer && pk.clustered != null
        ? (pk.clustered! ? ' CLUSTERED' : ' NONCLUSTERED')
        : '';
    return '${_named(pk.name)}PRIMARY KEY$clustered (${_cols(pk.columns)})${_deferrable(pk.state)}';
  }

  String _uniqueClause(UniqueDef u) => '${_named(u.name)}UNIQUE (${_cols(u.columns)})${_deferrable(u.state)}';

  String _checkClause(CheckDef c) => '${_named(c.name)}CHECK (${c.expression.trim()})';

  String _fkClause(ForeignKeyDef fk, TableDef owner) {
    final ref = dialect.qualified(fk.refCatalog, fk.refSchema, fk.refTable);
    final sb = StringBuffer(
      '${_named(fk.name)}FOREIGN KEY (${_cols(fk.columns)}) REFERENCES $ref (${_cols(fk.refColumns)})',
    );
    if (fk.match == FkMatch.full && family == DbFamily.postgres) sb.write(' MATCH FULL');
    final del = _rule(fk.onDelete, onUpdate: false);
    final upd = _rule(fk.onUpdate, onUpdate: true);
    if (del != null) sb.write(' ON DELETE $del');
    if (upd != null) sb.write(' ON UPDATE $upd');
    sb.write(_deferrable(fk.state, foreignKey: true));
    return sb.toString();
  }

  /// SQL for a referential action, or null when it is the default or not
  /// supported by the dialect (Oracle: no ON UPDATE, only CASCADE / SET NULL).
  String? _rule(FkRule r, {required bool onUpdate}) {
    if (r == FkRule.noAction) return null;
    switch (family) {
      case DbFamily.oracle:
        if (onUpdate) return null;
        return r == FkRule.cascade || r == FkRule.setNull ? r.sql : null;
      case DbFamily.sqlServer:
        return r == FkRule.restrict ? null : r.sql;
      case DbFamily.db2:
        if (onUpdate) return r == FkRule.restrict ? r.sql : null;
        return r == FkRule.setDefault ? null : r.sql;
      case DbFamily.mysql:
        return r == FkRule.setDefault ? null : r.sql;
      default:
        return r.sql;
    }
  }

  static ConstraintState _state(Object c) => switch (c) {
    PrimaryKeyDef x => x.state,
    UniqueDef x => x.state,
    CheckDef x => x.state,
    ForeignKeyDef x => x.state,
    _ => ConstraintState.standard,
  };

  static String? _constraintName(Object c) => switch (c) {
    PrimaryKeyDef x => x.name,
    UniqueDef x => x.name,
    CheckDef x => x.name,
    ForeignKeyDef x => x.name,
    _ => null,
  };

  static ConstraintKind _kind(Object c) => switch (c) {
    PrimaryKeyDef _ => ConstraintKind.primaryKey,
    UniqueDef _ => ConstraintKind.unique,
    CheckDef _ => ConstraintKind.check,
    _ => ConstraintKind.foreignKey,
  };

  /// `ALTER TABLE … ADD <clause>`, optionally without checking the existing
  /// rows (foreign keys and checks: PostgreSQL NOT VALID, SQL Server WITH
  /// NOCHECK, Oracle ENABLE NOVALIDATE, Db2 NOT ENFORCED).
  List<String> _addConstraint(TableDef t, String clause, {required bool noValidate, required String what}) {
    final table = tableRef(t);
    if (!noValidate || family == DbFamily.snowflake) return ['ALTER TABLE $table ADD $clause'];
    if (!caps.has(DesignFeature.addNotValidated)) {
      return [
        _comment('$what: ${caps.reason(DesignFeature.addNotValidated)}, i dati esistenti vengono verificati'),
        'ALTER TABLE $table ADD $clause',
      ];
    }
    return switch (family) {
      DbFamily.postgres => ['ALTER TABLE $table ADD $clause NOT VALID'],
      DbFamily.sqlServer => ['ALTER TABLE $table WITH NOCHECK ADD $clause'],
      DbFamily.oracle => ['ALTER TABLE $table ADD $clause ENABLE NOVALIDATE'],
      DbFamily.db2 => ['ALTER TABLE $table ADD $clause NOT ENFORCED'],
      _ => ['ALTER TABLE $table ADD $clause'],
    };
  }

  String _rebuildNote(TableDef t, String what) =>
      _comment('SQLite non consente di $what ${t.name}: ricostruire la tabella (non supportato)');

  List<String> addPrimaryKey(TableDef t, PrimaryKeyDef pk) {
    if (family == DbFamily.sqlite) return [_rebuildNote(t, 'aggiungere la chiave primaria a')];
    return ['ALTER TABLE ${tableRef(t)} ADD ${_pkClause(pk)}'];
  }

  List<String> dropPrimaryKey(TableDef t, PrimaryKeyDef pk) {
    final table = tableRef(t);
    final named = pk.name != null && pk.name!.isNotEmpty;
    switch (family) {
      case DbFamily.mysql || DbFamily.oracle || DbFamily.db2 || DbFamily.snowflake:
        return ['ALTER TABLE $table DROP PRIMARY KEY'];
      case DbFamily.sqlite:
        return [_rebuildNote(t, "eliminare la chiave primaria di")];
      case DbFamily.postgres:
        return ['ALTER TABLE $table DROP CONSTRAINT ${q(named ? pk.name! : '${t.name}_pkey')}'];
      default:
        if (!named) {
          return [
            _comment('Nome della chiave primaria di ${t.name} sconosciuto: eliminarla manualmente (non supportato)'),
          ];
        }
        return ['ALTER TABLE $table DROP CONSTRAINT ${q(pk.name!)}'];
    }
  }

  List<String> addUnique(TableDef t, UniqueDef u) {
    if (family == DbFamily.sqlite) return [_rebuildNote(t, 'aggiungere vincoli UNIQUE a')];
    return ['ALTER TABLE ${tableRef(t)} ADD ${_uniqueClause(u)}'];
  }

  List<String> dropUnique(TableDef t, UniqueDef u) {
    if (family == DbFamily.sqlite) return [_rebuildNote(t, 'eliminare vincoli UNIQUE da')];
    if (u.name == null || u.name!.isEmpty) {
      return [_comment('Vincolo UNIQUE senza nome su ${t.name}: eliminarlo manualmente (non supportato)')];
    }
    return [
      family == DbFamily.mysql
          ? 'ALTER TABLE ${tableRef(t)} DROP INDEX ${q(u.name!)}'
          : 'ALTER TABLE ${tableRef(t)} DROP CONSTRAINT ${q(u.name!)}',
    ];
  }

  List<String> addCheck(TableDef t, CheckDef c, {bool noValidate = false}) {
    if (family == DbFamily.sqlite) return [_rebuildNote(t, 'aggiungere vincoli CHECK a')];
    if (!caps.has(DesignFeature.checkConstraints)) {
      return [_comment2('Vincolo CHECK su ${t.name}: ${caps.reason(DesignFeature.checkConstraints)}')];
    }
    return _addConstraint(t, _checkClause(c), noValidate: noValidate, what: 'Vincolo CHECK ${c.name ?? ''}'.trim());
  }

  List<String> dropCheck(TableDef t, CheckDef c) {
    if (family == DbFamily.sqlite) return [_rebuildNote(t, 'eliminare vincoli CHECK da')];
    if (c.name == null || c.name!.isEmpty) {
      return [_comment('Vincolo CHECK senza nome su ${t.name}: eliminarlo manualmente (non supportato)')];
    }
    return [
      family == DbFamily.mysql && !_mariaDb
          ? 'ALTER TABLE ${tableRef(t)} DROP CHECK ${q(c.name!)}'
          : 'ALTER TABLE ${tableRef(t)} DROP CONSTRAINT ${q(c.name!)}',
    ];
  }

  List<String> addForeignKey(TableDef t, ForeignKeyDef fk, {bool noValidate = false}) {
    if (family == DbFamily.sqlite) return [_rebuildNote(t, 'aggiungere chiavi esterne a')];
    if (family == DbFamily.cassandra || family == DbFamily.bigquery) {
      return [_comment('Chiavi esterne non supportate da ${dialect.dbmsName} (non supportato)')];
    }
    return _addConstraint(t, _fkClause(fk, t), noValidate: noValidate, what: 'Chiave esterna ${fk.name ?? ''}'.trim());
  }

  List<String> dropForeignKey(TableDef t, ForeignKeyDef fk) {
    if (family == DbFamily.sqlite) return [_rebuildNote(t, 'eliminare chiavi esterne da')];
    if (fk.name == null || fk.name!.isEmpty) {
      return [_comment('Chiave esterna senza nome su ${t.name}: eliminarla manualmente (non supportato)')];
    }
    return [
      family == DbFamily.mysql
          ? 'ALTER TABLE ${tableRef(t)} DROP FOREIGN KEY ${q(fk.name!)}'
          : 'ALTER TABLE ${tableRef(t)} DROP CONSTRAINT ${q(fk.name!)}',
    ];
  }

  /// Adds [c] (a [PrimaryKeyDef], [UniqueDef], [CheckDef] or
  /// [ForeignKeyDef]) to the existing table [t].
  List<String> addConstraint(TableDef t, Object c, {bool noValidate = false}) => switch (c) {
    PrimaryKeyDef x => addPrimaryKey(t, x),
    UniqueDef x => addUnique(t, x),
    CheckDef x => addCheck(t, x, noValidate: noValidate),
    ForeignKeyDef x => addForeignKey(t, x, noValidate: noValidate),
    _ => throw ArgumentError.value(c, 'c', 'Vincolo sconosciuto'),
  };

  /// Drops the constraint [c] of [t].
  List<String> dropConstraint(TableDef t, Object c) => switch (c) {
    PrimaryKeyDef x => dropPrimaryKey(t, x),
    UniqueDef x => dropUnique(t, x),
    CheckDef x => dropCheck(t, x),
    ForeignKeyDef x => dropForeignKey(t, x),
    _ => throw ArgumentError.value(c, 'c', 'Vincolo sconosciuto'),
  };

  /// Renames the constraint [c] of [t] to [to]; DBMS without RENAME
  /// CONSTRAINT drop it and add it again.
  List<String> renameConstraint(TableDef t, Object c, String to) {
    final from = _constraintName(c);
    if (from == null || from.isEmpty) {
      return [_comment('Il vincolo da rinominare non ha nome (non supportato)')];
    }
    if (family == DbFamily.mysql && c is PrimaryKeyDef) {
      return [_comment('In MySQL la chiave primaria si chiama sempre PRIMARY (non supportato)')];
    }
    if (caps.has(DesignFeature.renameConstraint)) {
      if (family == DbFamily.sqlServer) {
        final path = dialect.qualified(null, t.schema, from);
        return ["EXEC sp_rename ${_n(path)}, ${_n(to)}, N'OBJECT'"];
      }
      return ['ALTER TABLE ${tableRef(t)} RENAME CONSTRAINT ${q(from)} TO ${q(to)}'];
    }
    if (family == DbFamily.sqlite) return [_rebuildNote(t, 'rinominare i vincoli di')];
    final renamed = switch (c) {
      PrimaryKeyDef x => x.copyWith(name: to),
      UniqueDef x => x.copyWith(name: to),
      CheckDef x => x.copyWith(name: to),
      ForeignKeyDef x => x.copyWith(name: to),
      _ => c,
    };
    return [...dropConstraint(t, c), ...addConstraint(t, renamed)];
  }

  /// Disables or enables the constraint [c] of [t]. Enabling checks the
  /// existing rows unless [validate] is false.
  List<String> setConstraintEnabled(TableDef t, Object c, bool enabled, {bool validate = true}) {
    final name = _constraintName(c);
    final kind = _kind(c);
    if (!caps.has(DesignFeature.disableConstraints)) {
      return [
        _comment2(
          '${enabled ? 'Abilitazione' : 'Disabilitazione'} del vincolo ${name ?? ''}: ${caps.reason(DesignFeature.disableConstraints)}',
        ),
      ];
    }
    if (name == null || name.isEmpty) return [_comment('Il vincolo non ha nome (non supportato)')];
    final table = tableRef(t), n = q(name);
    final fkOrCheck = kind == ConstraintKind.foreignKey || kind == ConstraintKind.check;
    switch (family) {
      case DbFamily.sqlServer:
        if (!fkOrCheck) return [_comment2('SQL Server disabilita solo chiavi esterne e vincoli CHECK')];
        if (!enabled) return ['ALTER TABLE $table NOCHECK CONSTRAINT $n'];
        return [
          validate ? 'ALTER TABLE $table WITH CHECK CHECK CONSTRAINT $n' : 'ALTER TABLE $table CHECK CONSTRAINT $n',
        ];
      case DbFamily.oracle:
        if (!enabled) return ['ALTER TABLE $table DISABLE CONSTRAINT $n'];
        return ['ALTER TABLE $table ENABLE ${validate ? '' : 'NOVALIDATE '}CONSTRAINT $n'];
      case DbFamily.db2:
        if (!fkOrCheck) return [_comment2('Db2 disabilita solo chiavi esterne e vincoli CHECK')];
        final what = kind == ConstraintKind.foreignKey ? 'FOREIGN KEY' : 'CHECK';
        return ['ALTER TABLE $table ALTER $what $n ${enabled ? 'ENFORCED' : 'NOT ENFORCED'}'];
      default:
        return [_comment2('Disabilitazione dei vincoli')];
    }
  }

  /// Checks the existing rows against the constraint [c] (added without
  /// validation or re-enabled without it).
  List<String> validateConstraint(TableDef t, Object c) {
    final name = _constraintName(c);
    if (name == null || name.isEmpty) return [_comment('Il vincolo non ha nome (non supportato)')];
    final table = tableRef(t), n = q(name);
    return switch (family) {
      DbFamily.postgres => ['ALTER TABLE $table VALIDATE CONSTRAINT $n'],
      DbFamily.sqlServer => ['ALTER TABLE $table WITH CHECK CHECK CONSTRAINT $n'],
      DbFamily.oracle => ['ALTER TABLE $table ENABLE VALIDATE CONSTRAINT $n'],
      DbFamily.db2 => setConstraintEnabled(t, c, true),
      _ => [_comment2('Validazione del vincolo $name')],
    };
  }

  /// Index name as written in DROP / ALTER INDEX: qualified with the schema
  /// of the table where indexes live in schemas.
  String _indexRef(TableDef t, IndexDef ix) => switch (family) {
    DbFamily.postgres ||
    DbFamily.oracle ||
    DbFamily.db2 ||
    DbFamily.sqlite => dialect.qualified(null, t.schema, ix.name),
    _ => q(ix.name),
  };

  /// CREATE INDEX with the options the DBMS supports; the others become
  /// notes. [online] builds it without locking writes (PostgreSQL
  /// CONCURRENTLY, which cannot run in a transaction).
  List<String> createIndex(TableDef t, IndexDef ix, {bool online = false}) {
    if (!caps.has(DesignFeature.indexes))
      return [_comment2('Indice ${ix.name}: ${caps.reason(DesignFeature.indexes)}')];
    final notes = <String>[];
    void unsupported(String what, DesignFeature f) => notes.add(
      _comment('Indice ${ix.name}: $what ignorato, ${caps.reason(f) ?? 'non supportato'} (non supportato)'),
    );

    final expressions = ix.columns.any(IndexDef.isExpression);
    final desc = ix.descending.isNotEmpty;
    if (desc && !caps.has(DesignFeature.indexDescending))
      unsupported('ordinamento DESC', DesignFeature.indexDescending);
    var include = ix.include;
    if (include.isNotEmpty && (!caps.has(DesignFeature.indexInclude) || (family == DbFamily.db2 && !ix.unique))) {
      unsupported('INCLUDE', DesignFeature.indexInclude);
      include = const [];
    }
    var where = ix.where?.trim() ?? '';
    if (where.isNotEmpty && !caps.has(DesignFeature.indexFilter)) {
      unsupported('filtro WHERE', DesignFeature.indexFilter);
      where = '';
    }
    if (online && !caps.has(DesignFeature.onlineIndex)) {
      unsupported('creazione online', DesignFeature.onlineIndex);
      online = false;
    }
    if (expressions && family == DbFamily.sqlServer) {
      return [_comment2('Indice ${ix.name}: SQL Server non indicizza espressioni, usa una colonna calcolata')];
    }
    final method = ix.method?.trim().toLowerCase();
    String col(String c) {
      if (IndexDef.isExpression(c)) {
        // Oracle and Db2 take a function call as is: lower(x), not (lower(x)).
        final inner = c.trim().substring(1, c.trim().length - 1).trim();
        final call = RegExp(r'^[A-Za-z_][\w.]*\s*\(.*\)$', dotAll: true).hasMatch(inner);
        return (family == DbFamily.oracle || family == DbFamily.db2) && call ? inner : c.trim();
      }
      return '${q(c)}${ix.isDescending(c) && caps.has(DesignFeature.indexDescending) ? ' DESC' : ''}';
    }

    final cols = ix.columns.map(col).join(', ');
    final table = tableRef(t), name = q(ix.name);
    final unique = ix.unique ? 'UNIQUE ' : '';
    final sb = StringBuffer();
    switch (family) {
      case DbFamily.postgres:
        sb.write('CREATE ${unique}INDEX ${online ? 'CONCURRENTLY ' : ''}$name ON $table');
        if (method != null && method.isNotEmpty && method != 'btree') sb.write(' USING $method');
        sb.write(' ($cols)');
        if (include.isNotEmpty) sb.write(' INCLUDE (${_cols(include)})');
        if (where.isNotEmpty) sb.write(' WHERE $where');
      case DbFamily.sqlServer:
        sb.write('CREATE $unique${ix.clustered ? 'CLUSTERED ' : ''}INDEX $name ON $table ($cols)');
        if (include.isNotEmpty) sb.write(' INCLUDE (${_cols(include)})');
        if (where.isNotEmpty) sb.write(' WHERE $where');
        if (online) sb.write(' WITH (ONLINE = ON)');
      case DbFamily.mysql:
        final using = method == 'hash' || method == 'btree' ? ' USING ${method!.toUpperCase()}' : '';
        final kind = method == 'fulltext' || method == 'spatial' ? '${method!.toUpperCase()} ' : unique;
        sb.write('CREATE ${kind}INDEX $name$using ON $table ($cols)');
        if (online) sb.write(' ALGORITHM=INPLACE LOCK=NONE');
      case DbFamily.oracle:
        final kind = method == 'bitmap' ? 'BITMAP ' : unique;
        sb.write('CREATE ${kind}INDEX ${_indexRef(t, ix)} ON $table ($cols)');
        if (online) sb.write(' ONLINE');
      case DbFamily.db2:
        sb.write('CREATE ${unique}INDEX ${_indexRef(t, ix)} ON $table ($cols)');
        if (include.isNotEmpty) sb.write(' INCLUDE (${_cols(include)})');
      case DbFamily.firebird:
        // Firebird: one direction for the whole index, one expression.
        if (desc && ix.descending.length != ix.columns.length) {
          notes.add(_comment('Indice ${ix.name}: Firebird ordina DESC tutte le colonne o nessuna (non supportato)'));
        }
        final allDesc = desc && ix.descending.length == ix.columns.length;
        sb.write('CREATE $unique${allDesc ? 'DESCENDING ' : ''}INDEX $name ON $table ');
        sb.write(expressions ? 'COMPUTED BY ${ix.columns.first.trim()}' : '(${_cols(ix.columns)})');
        if (where.isNotEmpty) sb.write(' WHERE $where');
      default:
        sb.write('CREATE ${unique}INDEX $name ON $table ($cols)');
        if (where.isNotEmpty) sb.write(' WHERE $where');
    }
    final out = [...notes, sb.toString()];
    if (!ix.enabled && caps.has(DesignFeature.disableIndex)) out.addAll(setIndexEnabled(t, ix, false));
    return out;
  }

  /// Renames the index [ix] of [t]; DBMS without RENAME INDEX recreate it.
  List<String> renameIndex(TableDef t, IndexDef ix, String to) {
    if (!caps.has(DesignFeature.indexes)) return [_comment2('Indici: ${caps.reason(DesignFeature.indexes)}')];
    if (!caps.has(DesignFeature.renameIndex)) {
      return [...dropIndex(t, ix), ...createIndex(t, ix.copyWith(name: to))];
    }
    final table = tableRef(t);
    return switch (family) {
      DbFamily.sqlServer => [
        "EXEC sp_rename ${_n('${dialect.qualified(null, t.schema, t.name)}.${q(ix.name)}')}, ${_n(to)}, N'INDEX'",
      ],
      DbFamily.mysql => ['ALTER TABLE $table RENAME INDEX ${q(ix.name)} TO ${q(to)}'],
      DbFamily.db2 => ['RENAME INDEX ${_indexRef(t, ix)} TO ${q(to)}'],
      _ => ['ALTER INDEX ${_indexRef(t, ix)} RENAME TO ${q(to)}'],
    };
  }

  /// Rebuilds the index [ix] (defragmentation, statistics).
  List<String> rebuildIndex(TableDef t, IndexDef ix) {
    final table = tableRef(t);
    return switch (family) {
      DbFamily.postgres => ['REINDEX INDEX ${_indexRef(t, ix)}'],
      DbFamily.sqlServer => ['ALTER INDEX ${q(ix.name)} ON $table REBUILD'],
      DbFamily.mysql => [
        _comment('MySQL ricostruisce tutti gli indici della tabella ${t.name}'),
        'OPTIMIZE TABLE $table',
      ],
      DbFamily.oracle => ['ALTER INDEX ${_indexRef(t, ix)} REBUILD'],
      DbFamily.db2 => ["CALL SYSPROC.ADMIN_CMD(${dialect.stringLiteral('REORG INDEXES ALL FOR TABLE $table')})"],
      DbFamily.sqlite => ['REINDEX ${_indexRef(t, ix)}'],
      DbFamily.firebird => ['ALTER INDEX ${q(ix.name)} ACTIVE'],
      _ => [_comment2('Ricostruzione dell\'indice ${ix.name}')],
    };
  }

  /// Disables (the optimizer ignores it, writes may skip it) or enables the
  /// index [ix].
  List<String> setIndexEnabled(TableDef t, IndexDef ix, bool enabled) {
    if (!caps.has(DesignFeature.disableIndex)) {
      return [_comment2('Disabilitazione dell\'indice ${ix.name}: ${caps.reason(DesignFeature.disableIndex)}')];
    }
    final table = tableRef(t), name = q(ix.name);
    return switch (family) {
      DbFamily.sqlServer => ['ALTER INDEX $name ON $table ${enabled ? 'REBUILD' : 'DISABLE'}'],
      DbFamily.mysql when _mariaDb => ['ALTER TABLE $table ALTER INDEX $name ${enabled ? 'NOT IGNORED' : 'IGNORED'}'],
      DbFamily.mysql => ['ALTER TABLE $table ALTER INDEX $name ${enabled ? 'VISIBLE' : 'INVISIBLE'}'],
      DbFamily.oracle => ['ALTER INDEX ${_indexRef(t, ix)} ${enabled ? 'REBUILD' : 'UNUSABLE'}'],
      DbFamily.firebird => ['ALTER INDEX $name ${enabled ? 'ACTIVE' : 'INACTIVE'}'],
      _ => [_comment2('Disabilitazione dell\'indice ${ix.name}')],
    };
  }

  List<String> dropIndex(TableDef t, IndexDef ix) {
    switch (family) {
      case DbFamily.sqlServer || DbFamily.mysql:
        return ['DROP INDEX ${q(ix.name)} ON ${tableRef(t)}'];
      case DbFamily.firebird:
        return ['DROP INDEX ${q(ix.name)}'];
      case DbFamily.sqlite:
        // SQLite schemas are attached database names ("main").
        return ['DROP INDEX ${dialect.qualified(null, t.schema, ix.name)}'];
      default:
        return ['DROP INDEX ${dialect.qualified(null, t.schema, ix.name)}'];
    }
  }

  // -------------------------------------------------------------------------
  // Comments
  // -------------------------------------------------------------------------

  bool get supportsComments => family != DbFamily.sqlite && family != DbFamily.cassandra;

  /// Sets (or removes when [comment] is empty) the comment of [t].
  List<String> tableComment(TableDef t, String? comment, {String? previous}) {
    final text = comment ?? '';
    switch (family) {
      case DbFamily.sqlite || DbFamily.cassandra:
        return const [];
      case DbFamily.mysql:
        return ['ALTER TABLE ${tableRef(t)} COMMENT = ${dialect.stringLiteral(text)}'];
      case DbFamily.sqlServer:
        return [_mssqlDescription(t, null, text, previous)];
      default:
        return ['COMMENT ON TABLE ${tableRef(t)} IS ${text.isEmpty ? 'NULL' : dialect.stringLiteral(text)}'];
    }
  }

  /// Sets (or removes) the comment of column [c] of [t].
  List<String> columnComment(TableDef t, ColumnDef c, {String? previous}) {
    final text = c.comment ?? '';
    switch (family) {
      case DbFamily.sqlite || DbFamily.cassandra:
        return const [];
      case DbFamily.mysql:
        return ['ALTER TABLE ${tableRef(t)} MODIFY COLUMN ${columnDefinition(c)}'];
      case DbFamily.sqlServer:
        return [_mssqlDescription(t, c.name, text, previous)];
      default:
        return [
          'COMMENT ON COLUMN ${tableRef(t)}.${q(c.name)} IS ${text.isEmpty ? 'NULL' : dialect.stringLiteral(text)}',
        ];
    }
  }

  String _mssqlDescription(TableDef t, String? column, String text, String? previous) {
    final hadPrevious = previous != null && previous.isNotEmpty;
    final proc = text.isEmpty
        ? 'sp_dropextendedproperty'
        : hadPrevious
        ? 'sp_updateextendedproperty'
        : 'sp_addextendedproperty';
    final sb = StringBuffer("EXEC $proc @name = N'MS_Description', ");
    if (text.isNotEmpty) sb.write('@value = ${_n(text)}, ');
    sb.write("@level0type = N'SCHEMA', @level0name = ${_n(t.schema ?? 'dbo')}, ");
    sb.write("@level1type = N'TABLE', @level1name = ${_n(t.name)}");
    if (column != null) sb.write(", @level2type = N'COLUMN', @level2name = ${_n(column)}");
    return sb.toString();
  }

  // -------------------------------------------------------------------------
  // SQLite table rebuild
  // -------------------------------------------------------------------------

  /// The procedure documented by SQLite for changes ALTER TABLE cannot do:
  /// create the new table, copy the data, drop the old one, rename.
  /// [from] is the current table, [to] the wanted definition (same location);
  /// [columnMap] maps new column names to the old ones whose data is copied.
  List<String> rebuildTable(TableDef from, TableDef to, Map<String, String> columnMap) {
    final tmpName = '${to.name}__new';
    final tmp = to.copyWith(name: tmpName, indexes: const []);
    final copied = [
      for (final c in to.columns)
        if (columnMap[c.name] != null) (c.name, columnMap[c.name]!),
    ];
    return [
      _comment('Ricostruzione della tabella ${from.name}: SQLite non supporta questa modifica con ALTER TABLE'),
      'PRAGMA foreign_keys = OFF',
      ...createTable(tmp, withIndexes: false, withComments: false),
      if (copied.isNotEmpty)
        'INSERT INTO ${tableRef(tmp)} (${_cols([for (final c in copied) c.$1])})\n'
            'SELECT ${_cols([for (final c in copied) c.$2])} FROM ${tableRef(from)}',
      'DROP TABLE ${tableRef(from)}',
      'ALTER TABLE ${tableRef(tmp)} RENAME TO ${q(to.name)}',
      for (final ix in to.indexes) ...createIndex(to, ix),
      'PRAGMA foreign_keys = ON',
    ];
  }

  // -------------------------------------------------------------------------
  // Ordering
  // -------------------------------------------------------------------------

  /// Orders [tables] so that referenced tables come before the tables that
  /// reference them (cycles keep their original order).
  static List<TableDef> sortByDependencies(List<TableDef> tables, {bool ignoreCase = true}) {
    String k(String s) => ignoreCase ? s.toLowerCase() : s;
    final byName = {for (final t in tables) k(t.name): t};
    final done = <String>{};
    final visiting = <String>{};
    final out = <TableDef>[];
    void visit(TableDef t) {
      final key = k(t.name);
      if (done.contains(key) || visiting.contains(key)) return;
      visiting.add(key);
      for (final fk in t.foreignKeys) {
        final dep = byName[k(fk.refTable)];
        if (dep != null && dep != t) visit(dep);
      }
      visiting.remove(key);
      done.add(key);
      out.add(t);
    }

    tables.forEach(visit);
    return out;
  }

  /// Full creation script for [tables]: tables in dependency order, then the
  /// foreign keys (so that cycles work), then comments.
  List<String> createSchema(List<TableDef> tables) {
    final sorted = sortByDependencies(tables);
    return [
      for (final t in sorted) ...createTable(t),
      if (family != DbFamily.sqlite)
        for (final t in sorted)
          for (final fk in t.foreignKeys) ...addForeignKey(t, fk),
    ];
  }

  /// Drop script for [tables]: foreign keys first, then tables in reverse
  /// dependency order.
  List<String> dropSchema(List<TableDef> tables) {
    final sorted = sortByDependencies(tables).reversed.toList();
    return [
      if (family != DbFamily.sqlite)
        for (final t in sorted)
          for (final fk in t.foreignKeys)
            if (fk.name != null && fk.name!.isNotEmpty) ...dropForeignKey(t, fk),
      for (final t in sorted) ...dropTable(t),
    ];
  }
}
