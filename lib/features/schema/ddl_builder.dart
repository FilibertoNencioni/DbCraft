// Dialect aware DDL generation (CREATE / ALTER / DROP) for tables, columns,
// keys, indexes and comments.
//
// Every method returns a list of statements WITHOUT terminators, ready to be
// executed one by one through ODBC (Oracle rejects a trailing ';'). Entries
// made only of `--` lines are comments: they are rendered in scripts and
// skipped on execution. [DdlBuilder.render] joins the statements into a script.

import '../../services/sql_dialect.dart';
import 'schema_model.dart';

/// True when [sql] contains only comments and blank lines.
bool isCommentOnly(String sql) => sql.split('\n').every((l) => l.trim().isEmpty || l.trimLeft().startsWith('--'));

/// Statements of [statements] that must be sent to the server.
List<String> executableStatements(List<String> statements) => statements.where((s) => !isCommentOnly(s)).toList();

class DdlBuilder {
  DdlBuilder(this.dialect);

  final SqlDialect dialect;

  DbFamily get family => dialect.family;

  String q(String name) => dialect.quoteIdent(name);

  String tableRef(TableDef t) => dialect.qualified(t.catalog, t.schema, t.name);

  String _cols(List<String> cols) => cols.map(q).join(', ');

  String _comment(String text) => text.split('\n').map((l) => '-- $l').join('\n');

  /// Joins [statements] into a script with `;` terminators.
  String render(List<String> statements) {
    final sb = StringBuffer();
    for (final s in statements) {
      if (isCommentOnly(s)) {
        if (sb.isNotEmpty && !sb.toString().endsWith('\n\n')) sb.writeln();
        sb.writeln(s);
      } else {
        sb.writeln('$s;');
        sb.writeln();
      }
    }
    return sb.toString().trimRight();
  }

  // -------------------------------------------------------------------------
  // Column definitions
  // -------------------------------------------------------------------------

  /// Type declaration of [c] for this dialect.
  String columnType(ColumnDef c) {
    final type = c.type.trim();
    if (type.contains('(') || c.size == null) return type;
    if (c.size == -1) {
      final canon = canonicalType(type);
      switch (family) {
        case DbFamily.sqlServer:
          return '$type(MAX)';
        case DbFamily.mysql:
          return canon.contains('binary') ? 'LONGBLOB' : 'LONGTEXT';
        case DbFamily.oracle:
          return canon.contains('binary') ? 'BLOB' : (canon == 'nvarchar' ? 'NCLOB' : 'CLOB');
        default:
          return type;
      }
    }
    if (c.scale != null && c.scale! > 0) return '$type(${c.size},${c.scale})';
    return '$type(${c.size})';
  }

  String? _identity(ColumnDef c) => switch (family) {
    DbFamily.sqlServer => 'IDENTITY(1,1)',
    DbFamily.mysql => null, // AUTO_INCREMENT is appended at the end
    DbFamily.sqlite => null, // only as INTEGER PRIMARY KEY AUTOINCREMENT
    DbFamily.snowflake => 'AUTOINCREMENT',
    DbFamily.bigquery || DbFamily.cassandra => null,
    _ => 'GENERATED BY DEFAULT AS IDENTITY',
  };

  /// Full column definition used by CREATE TABLE and ADD COLUMN.
  String columnDefinition(ColumnDef c, {bool sqliteRowId = false}) {
    final sb = StringBuffer('${q(c.name)} ${columnType(c)}');
    if (sqliteRowId) {
      sb.write(' PRIMARY KEY AUTOINCREMENT');
      return sb.toString();
    }
    if (c.autoIncrement) {
      final id = _identity(c);
      if (id != null) sb.write(' $id');
    }
    final def = c.defaultValue?.trim();
    if (!c.autoIncrement && def != null && def.isNotEmpty && family != DbFamily.cassandra) {
      sb.write(' DEFAULT $def');
    }
    if (!c.nullable && family != DbFamily.cassandra) sb.write(' NOT NULL');
    if (family == DbFamily.mysql) {
      if (c.autoIncrement) sb.write(' AUTO_INCREMENT');
      if (c.comment != null && c.comment!.isNotEmpty) sb.write(' COMMENT ${dialect.stringLiteral(c.comment!)}');
    }
    return sb.toString();
  }

  // -------------------------------------------------------------------------
  // Tables
  // -------------------------------------------------------------------------

  /// CREATE TABLE with columns and primary key. Foreign keys are created
  /// separately (after every table exists) unless [withForeignKeys]; SQLite
  /// always declares them inline because it cannot add them later.
  List<String> createTable(
    TableDef t, {
    bool withForeignKeys = false,
    bool withIndexes = true,
    bool withComments = true,
  }) {
    final pk = t.primaryKey;
    final pkCols = pk?.columns ?? const <String>[];
    // SQLite: an auto-increment column must be the INTEGER PRIMARY KEY.
    String? rowId;
    if (family == DbFamily.sqlite && pkCols.length == 1) {
      final c = t.column(pkCols.first);
      if (c != null && c.autoIncrement) rowId = c.name;
    }
    final lines = <String>[
      for (final c in t.columns)
        '\t${columnDefinition(c.name == rowId ? c.copyWith(type: 'INTEGER', size: null, scale: null) : c, sqliteRowId: c.name == rowId)}',
    ];
    if (pkCols.isNotEmpty && rowId == null) lines.add('\t${_pkClause(pk!)}');
    if (withForeignKeys || family == DbFamily.sqlite) {
      for (final fk in t.foreignKeys) {
        lines.add('\t${_fkClause(fk, t)}');
      }
    }
    final out = <String>['CREATE TABLE ${tableRef(t)} (\n${lines.join(',\n')}\n)'];
    if (family == DbFamily.mysql && t.comment != null && t.comment!.isNotEmpty) {
      out[0] = '${out[0]} COMMENT=${dialect.stringLiteral(t.comment!)}';
    }
    if (withIndexes) {
      for (final ix in t.indexes) {
        out.addAll(createIndex(t, ix));
      }
    }
    if (withComments && family != DbFamily.mysql) {
      if (t.comment != null && t.comment!.isNotEmpty) out.addAll(tableComment(t, t.comment));
      for (final c in t.columns) {
        if (c.comment != null && c.comment!.isNotEmpty) out.addAll(columnComment(t, c));
      }
    }
    return out;
  }

  List<String> dropTable(TableDef t) => [
    family == DbFamily.oracle ? 'DROP TABLE ${tableRef(t)} CASCADE CONSTRAINTS' : 'DROP TABLE ${tableRef(t)}',
  ];

  /// Renames [t] (current name) to [newName].
  List<String> renameTable(TableDef t, String newName) {
    final to = t.copyWith(name: newName);
    switch (family) {
      case DbFamily.sqlServer:
        final from = dialect.qualified(null, t.schema, t.name);
        return ['EXEC sp_rename ${_n(from)}, ${_n(newName)}'];
      case DbFamily.mysql:
        return ['RENAME TABLE ${tableRef(t)} TO ${tableRef(to)}'];
      case DbFamily.db2:
        return ['RENAME TABLE ${tableRef(t)} TO ${q(newName)}'];
      case DbFamily.firebird:
        return [_comment('Firebird non supporta la ridenominazione di tabelle: ${t.name} → $newName (non supportato)')];
      default:
        return ['ALTER TABLE ${tableRef(t)} RENAME TO ${q(newName)}'];
    }
  }

  /// N'…' literal for SQL Server system procedures.
  String _n(String s) => 'N${dialect.stringLiteral(s)}';

  // -------------------------------------------------------------------------
  // Columns
  // -------------------------------------------------------------------------

  List<String> addColumn(TableDef t, ColumnDef c) {
    final def = columnDefinition(c);
    final out = <String>[];
    if (!c.nullable && (c.defaultValue == null || c.defaultValue!.trim().isEmpty) && !c.autoIncrement) {
      out.add(_comment('Attenzione: ${c.name} è NOT NULL senza DEFAULT, fallisce se la tabella contiene righe'));
    }
    switch (family) {
      case DbFamily.sqlServer || DbFamily.oracle || DbFamily.firebird:
        out.add('ALTER TABLE ${tableRef(t)} ADD $def');
      default:
        out.add('ALTER TABLE ${tableRef(t)} ADD COLUMN $def');
    }
    if (family != DbFamily.mysql && c.comment != null && c.comment!.isNotEmpty) out.addAll(columnComment(t, c));
    return out;
  }

  List<String> dropColumn(TableDef t, String column) => [
    family == DbFamily.firebird
        ? 'ALTER TABLE ${tableRef(t)} DROP ${q(column)}'
        : 'ALTER TABLE ${tableRef(t)} DROP COLUMN ${q(column)}',
  ];

  List<String> renameColumn(TableDef t, String from, String to) {
    switch (family) {
      case DbFamily.sqlServer:
        final path = '${dialect.qualified(null, t.schema, t.name)}.${q(from)}';
        return ["EXEC sp_rename ${_n(path)}, ${_n(to)}, 'COLUMN'"];
      case DbFamily.firebird:
        return ['ALTER TABLE ${tableRef(t)} ALTER COLUMN ${q(from)} TO ${q(to)}'];
      default:
        return ['ALTER TABLE ${tableRef(t)} RENAME COLUMN ${q(from)} TO ${q(to)}'];
    }
  }

  /// Changes type, nullability and default of a column from [from] to [to]
  /// ([to].name is the current name of the column).
  List<String> alterColumn(TableDef t, ColumnDef from, ColumnDef to) {
    final table = tableRef(t);
    final col = q(to.name);
    final typeChanged = columnType(from).toLowerCase() != columnType(to).toLowerCase();
    final nullChanged = from.nullable != to.nullable;
    final defChanged = normalizeDefault(from.defaultValue) != normalizeDefault(to.defaultValue);
    final autoChanged = from.autoIncrement != to.autoIncrement;
    final commentChanged = (from.comment ?? '') != (to.comment ?? '');
    final newDef = to.defaultValue?.trim();
    final hasDef = newDef != null && newDef.isNotEmpty;
    final out = <String>[];
    if (autoChanged && family != DbFamily.mysql) {
      out.add(
        _comment(
          'La modifica di identity/auto-increment di ${to.name} richiede di ricreare la colonna (non supportato)',
        ),
      );
    }
    switch (family) {
      case DbFamily.mysql:
        if (typeChanged || nullChanged || defChanged || autoChanged || commentChanged) {
          out.add('ALTER TABLE $table MODIFY COLUMN ${columnDefinition(to)}');
        }
        return out;
      case DbFamily.sqlServer:
        if (typeChanged || nullChanged) {
          out.add('ALTER TABLE $table ALTER COLUMN $col ${columnType(to)}${to.nullable ? ' NULL' : ' NOT NULL'}');
        }
        if (defChanged) {
          if (from.defaultValue != null && from.defaultValue!.trim().isNotEmpty) out.add(_mssqlDropDefault(t, to.name));
          if (hasDef) out.add('ALTER TABLE $table ADD DEFAULT $newDef FOR $col');
        }
      case DbFamily.oracle:
        final parts = <String>[
          if (typeChanged) columnType(to),
          if (defChanged) 'DEFAULT ${hasDef ? newDef : 'NULL'}',
          if (nullChanged) to.nullable ? 'NULL' : 'NOT NULL',
        ];
        if (parts.isNotEmpty) out.add('ALTER TABLE $table MODIFY ($col ${parts.join(' ')})');
      case DbFamily.postgres || DbFamily.generic:
        if (typeChanged) {
          final using = family == DbFamily.postgres ? ' USING $col::${columnType(to)}' : '';
          out.add('ALTER TABLE $table ALTER COLUMN $col TYPE ${columnType(to)}$using');
        }
        if (nullChanged) out.add('ALTER TABLE $table ALTER COLUMN $col ${to.nullable ? 'DROP' : 'SET'} NOT NULL');
        if (defChanged) {
          out.add('ALTER TABLE $table ALTER COLUMN $col ${hasDef ? 'SET DEFAULT $newDef' : 'DROP DEFAULT'}');
        }
      case DbFamily.db2 || DbFamily.snowflake:
        if (typeChanged) out.add('ALTER TABLE $table ALTER COLUMN $col SET DATA TYPE ${columnType(to)}');
        if (nullChanged) out.add('ALTER TABLE $table ALTER COLUMN $col ${to.nullable ? 'DROP' : 'SET'} NOT NULL');
        if (defChanged) {
          if (family == DbFamily.snowflake && hasDef) {
            out.add(
              _comment(
                'Snowflake non consente di impostare il DEFAULT di ${to.name} su una colonna esistente (non supportato)',
              ),
            );
          } else {
            out.add('ALTER TABLE $table ALTER COLUMN $col ${hasDef ? 'SET DEFAULT $newDef' : 'DROP DEFAULT'}');
          }
        }
        if (family == DbFamily.db2 && (typeChanged || nullChanged)) {
          out.add(_comment("Potrebbe essere necessario: CALL SYSPROC.ADMIN_CMD('REORG TABLE $table')"));
        }
      case DbFamily.firebird:
        if (typeChanged) out.add('ALTER TABLE $table ALTER COLUMN $col TYPE ${columnType(to)}');
        if (nullChanged) out.add('ALTER TABLE $table ALTER $col ${to.nullable ? 'DROP' : 'SET'} NOT NULL');
        if (defChanged) {
          out.add('ALTER TABLE $table ALTER COLUMN $col ${hasDef ? 'SET DEFAULT $newDef' : 'DROP DEFAULT'}');
        }
      case DbFamily.sqlite:
        if (typeChanged || nullChanged || defChanged || autoChanged) {
          out.add(
            _comment(
              'SQLite non supporta ALTER COLUMN su ${to.name}: è necessario ricostruire la tabella (non supportato)',
            ),
          );
        }
      default:
        if (typeChanged || nullChanged || defChanged) {
          out.add(_comment('Modifica della colonna ${to.name} non supportata da ${dialect.dbmsName} (non supportato)'));
        }
    }
    if (commentChanged) out.addAll(columnComment(t, to, previous: from.comment));
    return out;
  }

  /// SQL Server keeps defaults in named constraints: look the name up and drop it.
  String _mssqlDropDefault(TableDef t, String column) {
    final obj = dialect.qualified(null, t.schema, t.name);
    return 'DECLARE @df sysname\n'
        'SELECT @df = dc.name FROM sys.default_constraints dc '
        'JOIN sys.columns c ON c.object_id = dc.parent_object_id AND c.column_id = dc.parent_column_id '
        'WHERE dc.parent_object_id = OBJECT_ID(${_n(obj)}) AND c.name = ${_n(column)}\n'
        "IF @df IS NOT NULL EXEC(N'ALTER TABLE ${obj.replaceAll("'", "''")} DROP CONSTRAINT [' + @df + N']')";
  }

  // -------------------------------------------------------------------------
  // Constraints and indexes
  // -------------------------------------------------------------------------

  String _pkClause(PrimaryKeyDef pk) {
    final name = pk.name != null && pk.name!.isNotEmpty ? 'CONSTRAINT ${q(pk.name!)} ' : '';
    return '${name}PRIMARY KEY (${_cols(pk.columns)})';
  }

  String _fkClause(ForeignKeyDef fk, TableDef owner) {
    final name = fk.name != null && fk.name!.isNotEmpty ? 'CONSTRAINT ${q(fk.name!)} ' : '';
    final ref = dialect.qualified(fk.refCatalog, fk.refSchema, fk.refTable);
    final sb = StringBuffer('${name}FOREIGN KEY (${_cols(fk.columns)}) REFERENCES $ref (${_cols(fk.refColumns)})');
    final del = _rule(fk.onDelete, onUpdate: false);
    final upd = _rule(fk.onUpdate, onUpdate: true);
    if (del != null) sb.write(' ON DELETE $del');
    if (upd != null) sb.write(' ON UPDATE $upd');
    return sb.toString();
  }

  /// SQL for a referential action, or null when it is the default or not
  /// supported by the dialect (Oracle: no ON UPDATE, only CASCADE / SET NULL).
  String? _rule(FkRule r, {required bool onUpdate}) {
    if (r == FkRule.noAction) return null;
    switch (family) {
      case DbFamily.oracle:
        if (onUpdate) return null;
        return r == FkRule.cascade || r == FkRule.setNull ? r.sql : null;
      case DbFamily.sqlServer:
        return r == FkRule.restrict ? null : r.sql;
      case DbFamily.db2:
        if (onUpdate) return r == FkRule.restrict ? r.sql : null;
        return r.sql;
      default:
        return r.sql;
    }
  }

  List<String> addPrimaryKey(TableDef t, PrimaryKeyDef pk) {
    if (family == DbFamily.sqlite) {
      return [
        _comment(
          'SQLite non consente di aggiungere la chiave primaria a ${t.name}: ricostruire la tabella (non supportato)',
        ),
      ];
    }
    return ['ALTER TABLE ${tableRef(t)} ADD ${_pkClause(pk)}'];
  }

  List<String> dropPrimaryKey(TableDef t, PrimaryKeyDef pk) {
    final table = tableRef(t);
    final named = pk.name != null && pk.name!.isNotEmpty;
    switch (family) {
      case DbFamily.mysql || DbFamily.oracle || DbFamily.db2 || DbFamily.snowflake:
        return ['ALTER TABLE $table DROP PRIMARY KEY'];
      case DbFamily.sqlite:
        return [
          _comment(
            'SQLite non consente di eliminare la chiave primaria di ${t.name}: ricostruire la tabella (non supportato)',
          ),
        ];
      case DbFamily.postgres:
        return ['ALTER TABLE $table DROP CONSTRAINT ${q(named ? pk.name! : '${t.name}_pkey')}'];
      default:
        if (!named) {
          return [
            _comment('Nome della chiave primaria di ${t.name} sconosciuto: eliminarla manualmente (non supportato)'),
          ];
        }
        return ['ALTER TABLE $table DROP CONSTRAINT ${q(pk.name!)}'];
    }
  }

  List<String> addForeignKey(TableDef t, ForeignKeyDef fk) {
    if (family == DbFamily.sqlite) {
      return [
        _comment(
          'SQLite non consente di aggiungere chiavi esterne a ${t.name}: ricostruire la tabella (non supportato)',
        ),
      ];
    }
    if (family == DbFamily.cassandra || family == DbFamily.bigquery) {
      return [_comment('Chiavi esterne non supportate da ${dialect.dbmsName} (non supportato)')];
    }
    return ['ALTER TABLE ${tableRef(t)} ADD ${_fkClause(fk, t)}'];
  }

  List<String> dropForeignKey(TableDef t, ForeignKeyDef fk) {
    if (family == DbFamily.sqlite) {
      return [
        _comment(
          'SQLite non consente di eliminare chiavi esterne da ${t.name}: ricostruire la tabella (non supportato)',
        ),
      ];
    }
    if (fk.name == null || fk.name!.isEmpty) {
      return [_comment('Chiave esterna senza nome su ${t.name}: eliminarla manualmente (non supportato)')];
    }
    return [
      family == DbFamily.mysql
          ? 'ALTER TABLE ${tableRef(t)} DROP FOREIGN KEY ${q(fk.name!)}'
          : 'ALTER TABLE ${tableRef(t)} DROP CONSTRAINT ${q(fk.name!)}',
    ];
  }

  List<String> createIndex(TableDef t, IndexDef ix) => [
    'CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${q(ix.name)} ON ${tableRef(t)} (${_cols(ix.columns)})',
  ];

  List<String> dropIndex(TableDef t, IndexDef ix) {
    switch (family) {
      case DbFamily.sqlServer || DbFamily.mysql:
        return ['DROP INDEX ${q(ix.name)} ON ${tableRef(t)}'];
      case DbFamily.firebird:
        return ['DROP INDEX ${q(ix.name)}'];
      case DbFamily.sqlite:
        // SQLite schemas are attached database names ("main").
        return ['DROP INDEX ${dialect.qualified(null, t.schema, ix.name)}'];
      default:
        return ['DROP INDEX ${dialect.qualified(null, t.schema, ix.name)}'];
    }
  }

  // -------------------------------------------------------------------------
  // Comments
  // -------------------------------------------------------------------------

  bool get supportsComments => family != DbFamily.sqlite && family != DbFamily.cassandra;

  /// Sets (or removes when [comment] is empty) the comment of [t].
  List<String> tableComment(TableDef t, String? comment, {String? previous}) {
    final text = comment ?? '';
    switch (family) {
      case DbFamily.sqlite || DbFamily.cassandra:
        return const [];
      case DbFamily.mysql:
        return ['ALTER TABLE ${tableRef(t)} COMMENT = ${dialect.stringLiteral(text)}'];
      case DbFamily.sqlServer:
        return [_mssqlDescription(t, null, text, previous)];
      default:
        return ['COMMENT ON TABLE ${tableRef(t)} IS ${text.isEmpty ? 'NULL' : dialect.stringLiteral(text)}'];
    }
  }

  /// Sets (or removes) the comment of column [c] of [t].
  List<String> columnComment(TableDef t, ColumnDef c, {String? previous}) {
    final text = c.comment ?? '';
    switch (family) {
      case DbFamily.sqlite || DbFamily.cassandra:
        return const [];
      case DbFamily.mysql:
        return ['ALTER TABLE ${tableRef(t)} MODIFY COLUMN ${columnDefinition(c)}'];
      case DbFamily.sqlServer:
        return [_mssqlDescription(t, c.name, text, previous)];
      default:
        return [
          'COMMENT ON COLUMN ${tableRef(t)}.${q(c.name)} IS ${text.isEmpty ? 'NULL' : dialect.stringLiteral(text)}',
        ];
    }
  }

  String _mssqlDescription(TableDef t, String? column, String text, String? previous) {
    final hadPrevious = previous != null && previous.isNotEmpty;
    final proc = text.isEmpty
        ? 'sp_dropextendedproperty'
        : hadPrevious
        ? 'sp_updateextendedproperty'
        : 'sp_addextendedproperty';
    final sb = StringBuffer("EXEC $proc @name = N'MS_Description', ");
    if (text.isNotEmpty) sb.write('@value = ${_n(text)}, ');
    sb.write("@level0type = N'SCHEMA', @level0name = ${_n(t.schema ?? 'dbo')}, ");
    sb.write("@level1type = N'TABLE', @level1name = ${_n(t.name)}");
    if (column != null) sb.write(", @level2type = N'COLUMN', @level2name = ${_n(column)}");
    return sb.toString();
  }

  // -------------------------------------------------------------------------
  // SQLite table rebuild
  // -------------------------------------------------------------------------

  /// The procedure documented by SQLite for changes ALTER TABLE cannot do:
  /// create the new table, copy the data, drop the old one, rename.
  /// [from] is the current table, [to] the wanted definition (same location);
  /// [columnMap] maps new column names to the old ones whose data is copied.
  List<String> rebuildTable(TableDef from, TableDef to, Map<String, String> columnMap) {
    final tmpName = '${to.name}__new';
    final tmp = to.copyWith(name: tmpName, indexes: const []);
    final copied = [
      for (final c in to.columns)
        if (columnMap[c.name] != null) (c.name, columnMap[c.name]!),
    ];
    return [
      _comment('Ricostruzione della tabella ${from.name}: SQLite non supporta questa modifica con ALTER TABLE'),
      'PRAGMA foreign_keys = OFF',
      ...createTable(tmp, withIndexes: false, withComments: false),
      if (copied.isNotEmpty)
        'INSERT INTO ${tableRef(tmp)} (${_cols([for (final c in copied) c.$1])})\n'
            'SELECT ${_cols([for (final c in copied) c.$2])} FROM ${tableRef(from)}',
      'DROP TABLE ${tableRef(from)}',
      'ALTER TABLE ${tableRef(tmp)} RENAME TO ${q(to.name)}',
      for (final ix in to.indexes) ...createIndex(to, ix),
      'PRAGMA foreign_keys = ON',
    ];
  }

  // -------------------------------------------------------------------------
  // Ordering
  // -------------------------------------------------------------------------

  /// Orders [tables] so that referenced tables come before the tables that
  /// reference them (cycles keep their original order).
  static List<TableDef> sortByDependencies(List<TableDef> tables, {bool ignoreCase = true}) {
    String k(String s) => ignoreCase ? s.toLowerCase() : s;
    final byName = {for (final t in tables) k(t.name): t};
    final done = <String>{};
    final visiting = <String>{};
    final out = <TableDef>[];
    void visit(TableDef t) {
      final key = k(t.name);
      if (done.contains(key) || visiting.contains(key)) return;
      visiting.add(key);
      for (final fk in t.foreignKeys) {
        final dep = byName[k(fk.refTable)];
        if (dep != null && dep != t) visit(dep);
      }
      visiting.remove(key);
      done.add(key);
      out.add(t);
    }

    tables.forEach(visit);
    return out;
  }

  /// Full creation script for [tables]: tables in dependency order, then the
  /// foreign keys (so that cycles work), then comments.
  List<String> createSchema(List<TableDef> tables) {
    final sorted = sortByDependencies(tables);
    return [
      for (final t in sorted) ...createTable(t),
      if (family != DbFamily.sqlite)
        for (final t in sorted)
          for (final fk in t.foreignKeys) ...addForeignKey(t, fk),
    ];
  }

  /// Drop script for [tables]: foreign keys first, then tables in reverse
  /// dependency order.
  List<String> dropSchema(List<TableDef> tables) {
    final sorted = sortByDependencies(tables).reversed.toList();
    return [
      if (family != DbFamily.sqlite)
        for (final t in sorted)
          for (final fk in t.foreignKeys)
            if (fk.name != null && fk.name!.isNotEmpty) ...dropForeignKey(t, fk),
      for (final t in sorted) ...dropTable(t),
    ];
  }
}
